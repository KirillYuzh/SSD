package ru.mtuci.rbpo.lab4.domain;

/**
 * Статусы размещения животного в приюте
 */
public enum AnimalStatus {
    /** Животное находится в приюте и доступно для усыновления */
    AVAILABLE,

    /** По животному одобрена заявка, оно закреплено за будущей семьёй */
    RESERVED,

    /** Животное передано семье, подтверждено актом передачи */
    HANDED_OVER,
}
