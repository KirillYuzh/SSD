-- Запуск от суперпользователя: psql -U postgres -f db/init.sql
-- Скрипт пересоздаёт базу shelter и наполняет её демонстрационными данными.

DROP DATABASE IF EXISTS shelter WITH (FORCE);
DROP ROLE IF EXISTS shelter_app;

CREATE ROLE shelter_app LOGIN PASSWORD 'shelter_app' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE DATABASE shelter;

\connect shelter

CREATE TABLE users
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR(32)  NOT NULL UNIQUE,
    full_name VARCHAR(128) NOT NULL,
    email     VARCHAR(254) NOT NULL UNIQUE,
    password  VARCHAR(100) NOT NULL,
    role      VARCHAR(32)  NOT NULL,
    status    VARCHAR(32)  NOT NULL,
    CONSTRAINT users_role_check CHECK (role IN ('ADOPTER', 'STAFF')),
    CONSTRAINT users_status_check CHECK (status IN ('ACTIVE', 'BLOCKED'))
);

CREATE TABLE enclosures
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(64) NOT NULL,
    capacity INTEGER     NOT NULL,
    CONSTRAINT enclosures_capacity_check CHECK (capacity > 0)
);

-- Допустимые виды животных хранятся в отдельной таблице, одна строка на вид.
CREATE TABLE enclosure_species
(
    enclosure_id BIGINT      NOT NULL REFERENCES enclosures (id) ON DELETE CASCADE,
    species      VARCHAR(64) NOT NULL,
    PRIMARY KEY (enclosure_id, species)
);

CREATE TABLE animals
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(64) NOT NULL,
    species      VARCHAR(64) NOT NULL,
    age          INTEGER     NOT NULL,
    status       VARCHAR(32) NOT NULL,
    enclosure_id BIGINT      REFERENCES enclosures (id),
    CONSTRAINT animals_age_check CHECK (age >= 0),
    CONSTRAINT animals_status_check CHECK (status IN ('AVAILABLE', 'RESERVED', 'HANDED_OVER'))
);

CREATE INDEX idx_animals_enclosure ON animals (enclosure_id);

-- Одна заявка на пару «животное — заявитель», статусы ограничены перечислением.
CREATE TABLE adoption_applications
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id    BIGINT      NOT NULL REFERENCES animals (id),
    applicant_id BIGINT      NOT NULL REFERENCES users (id),
    motivation   VARCHAR(500),
    status       VARCHAR(32) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT adoption_applications_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT adoption_applications_participants_unique UNIQUE (animal_id, applicant_id)
);

CREATE INDEX idx_adoption_applications_animal ON adoption_applications (animal_id);
CREATE INDEX idx_adoption_applications_applicant ON adoption_applications (applicant_id);

-- По заявке оформляется не более одного акта; дата подтверждения есть только у
-- подтверждённого и возвращённого акта.
CREATE TABLE animal_handover_records
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id    BIGINT      NOT NULL UNIQUE REFERENCES adoption_applications (id),
    preparation_date  DATE        NOT NULL,
    confirmation_date DATE,
    status            VARCHAR(32) NOT NULL,
    CONSTRAINT animal_handover_records_status_check
        CHECK (status IN ('PREPARED', 'CONFIRMED', 'RETURNED')),
    CONSTRAINT animal_handover_records_confirmation_check
        CHECK ((status IN ('CONFIRMED', 'RETURNED')) = (confirmation_date IS NOT NULL))
);

