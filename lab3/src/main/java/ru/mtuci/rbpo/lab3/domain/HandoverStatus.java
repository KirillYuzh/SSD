package ru.mtuci.rbpo.lab3.domain;

/**
 * Статусы акта передачи животного
 */
public enum HandoverStatus {
    /** Акт подготовлен приютом, дата подтверждения ещё не наступила */
    PREPARED,

    /** Акт подтверждён семьёй, животное передано */
    CONFIRMED,

    /** Животное возвращено в приют, передача отменена */
    RETURNED,
}
